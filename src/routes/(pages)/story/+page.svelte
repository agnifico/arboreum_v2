<p class="kicker">STORY · DESIGN AND PHILOSOPHY</p>
<h1>Customisation within structure.</h1>
<p class="lead">
  The 1610F is a conceptual design project: the specialised handheld electronics of the past, meeting modern web design. It
  asks what a notes app would feel like if it were an object you could pick up, with keys that click and modules that slot in.
</p>

<h2><span class="no">01</span>Where it comes from</h2>
<p>
  Arboreum began as a cosy notebook where every note grows into a pixel tree, and the trees grow into a garden. That first
  interface is still here as <a href="/classic">the classic app</a>, on the same notes.
</p>
<p>
  The 1610F keeps the garden and changes everything around it. The interface became a console. The writing became plain and
  monospaced, like a code editor: calm, even and line by line. The tools became modules: free-standing bodies with screws and
  printed labels, each with one job, which together make the device.
</p>

<h2><span class="no">02</span>Three rules underneath</h2>

<h3>Concept never beats usability</h3>
<p>
  The hardware is a skin over a tool people actually use. Everyday features stay even when they don't map neatly onto a
  console. Picking several notes and deleting them is one: there's no obvious button for it on a handheld, so it got a
  slider of its own.
</p>

<h3>Three equivalent ways to do everything</h3>
<p>Every action has three complete routes, and each one works on its own:</p>
<ol>
  <li><strong>The classic desktop.</strong> Keyboard shortcuts and the mouse, the way any app works.</li>
  <li><strong>Touching the console.</strong> Pressing the hardware with the cursor or a finger, as on a touch-screen device.</li>
  <li><strong>The console way.</strong> Only the D-pad, A, B and Start, with menus.</li>
</ol>
<p>
  They overlap on purpose, and you can switch mid-action: press MOVE on the map, nudge with the arrow keys, finish with the
  mouse. Whatever hand is already moving should just work. The aim is a device that feels smooth in a way nobody can quite
  explain.
</p>
<p class="note">
  One thing it deliberately doesn't do: the strip that says what A and B do is a label, never a button. The keys are real, and
  the screen itself is clickable, so the routes join up without that shortcut.
</p>

<h3>Hardware is a layout tool</h3>
<p>
  The physical metaphor decides the rules, and the web decides how the space flows. Controls always sit below the screen. Each
  side of the screen holds at most one dock. Pull the speaker and the map viewer takes its column and zooms in. Pull the map
  and the screen widens into the space. Modules that exist only for the look give way to ones that do something.
</p>

<h2><span class="no">03</span>Structure, then freedom</h2>
<p>
  You choose what's slotted, but not where it goes. A handful of placement rules arrange any combination, so it never needs
  dragging around and never ends up broken. The same goes for colour: a theme colours every module and the accent together,
  never one module at a time, so the contrast between them stays designed instead of left to chance.
</p>
<p>
  Only the screen stretches. On a bigger window the screen takes the extra room and every other module keeps its size, the
  way a real device's keys don't grow. On a smaller one the whole console scales down together. Upright windows get their
  own arrangement, a stack shaped to a phone, and the console follows as you turn the device.
</p>

<h2><span class="no">04</span>The details</h2>
<ul>
  <li><strong>Printing and screens.</strong> Chakra Petch is the printing on the hardware; JetBrains Mono is on the screens.</li>
  <li><strong>Model numbers are hexadecimal.</strong> The 1610F is <code>0x1610F</code>.</li>
  <li><strong>One accent.</strong> In each theme, a single signal colour marks what's live: the A key, LEDs, latches, the cursor and the stripe on the nameplate.</li>
  <li><strong>The screen tells you where you are.</strong> Its glass is a warm moss while you write and a cool slate while you browse.</li>
  <li><strong>The keys don't steal focus.</strong> Pressing a console key never takes the cursor out of your text, so you can type, press, and keep typing.</li>
</ul>
