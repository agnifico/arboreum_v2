<p class="kicker">ABOUT · THE APP</p>
<h1>Classic note taking, reimagined.</h1>
<p class="lead">
  Arboreum is a notebook where every note grows into a tree on a little map. <br>The <i>JXF26-ARB-16A</i> presents it as a
  piece of modular hardware: a console of modules you can slot in and out, with a screen for writing in the middle.
</p>

<h2><span class="no">01</span>What it is</h2>
<p>
  <strong>Writing is plain and calm.</strong> The screen is a monospace editor in the classic code-editor style: line numbers, a
  current-line band and an orange block cursor. Bold, italics, headings, lists, tasks, quotes and code are all there, drawn
  so every line stays on the grid.
</p>
<p>
  <strong>Every note is a tree.</strong> Pick one of the pixel trees for a note and plant it on a plot of the garden map.
  Over time your notes become a garden you can wander, and tapping a tree opens its note.
</p>
<p>
  <strong>The interface is hardware.</strong> Around the screen sit modules: a D-pad, A and B keys, a camera for images, a map
  viewer, a little tree buddy. Each one is a real control. You can still click, tap and type as in any app.
</p>

