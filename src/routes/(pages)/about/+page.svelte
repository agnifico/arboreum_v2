  The gear in the nameplate opens <strong>Configure</strong>: choose what's slotted (LAYOUT) and the console's colours (LOOK).
</p>

<h2><span class="no">03</span>Your notes stay with you</h2>
<p>
  There is no account and no server. Notes are kept in this browser, and images in the browser's private file storage. That
  also means they live on this device only: a different browser or another computer starts empty.
</p>
<p class="note">
  Back up now and then: press <kbd>START</kbd>, then <strong>BACKUP → SAVE</strong>. <strong>LOAD</strong> brings a backup back. Images
  aren't in backups yet.
</p>

