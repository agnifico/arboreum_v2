<h1>Help and tutorials</h1>
<p class="lead">
  The device opens straight into a note, ready to write. Everything else is a key away, and every action works three ways:
  with your keyboard and mouse, by touching the console, or with the console keys alone.
</p>

<h2><span class="no">01</span>Quick start</h2>
<ol>
  <li><strong>Write.</strong> Click the screen and type.</li>
  <li><strong>Save.</strong> Press <kbd class="a">A</kbd> or <code>Ctrl/⌘ S</code>. Leaving a note always saves it too.</li>
  <li><strong>Start a new note.</strong> Press <kbd>B</kbd>. The note you were on is saved first.</li>
  <li><strong>Give it a tree.</strong> On the Map viewer, press <kbd class="key">TREE</kbd> and pick one.</li>
  <li><strong>Plant it.</strong> Press <kbd class="key">MOVE</kbd>, move to a free plot, and press <kbd class="a">A</kbd>. Or click a tile, then click it again.</li>
  <li><strong>Find your notes.</strong> Press <kbd>SELECT</kbd> (or <code>Ctrl/⌘ L</code>) for the list. <kbd class="a">A</kbd> opens a note.</li>
</ol>

