<h2><span class="no">04</span>Tutorials</h2>

<h3>Formatting</h3>
<p>Three ways, mix as you like:</p>
<ul>
  <li><strong>Type it.</strong> Start a line with <code>- </code> for a bullet, <code>1. </code> for a numbered list or <code>[ ] </code> for a task. <code>Ctrl/⌘ B</code>, <code>I</code> and <code>U</code> work as usual. Tab and Shift+Tab nest list items.</li>
  <li><strong>The format strip</strong> along the bottom of the screen: undo and redo, the marks, headings, lists, indent, and IMG. <kbd class="key">◀</kbd> <kbd class="key">▶</kbd> switch it to DETAILS (words, dates, tree, plot).</li>
  <li><strong>The Format deck.</strong> Flip the accent-coloured switch on the control pad's right edge (or choose it in Configure) and real keys slide in. A key stays down while its format is under the cursor.</li>
</ul>
<p>Configure → <strong>SHOW MARKUP</strong> shows the markers (<code>**</code>, <code>#</code>, <code>- </code>) as text instead.</p>

<h3>Images</h3>
<ul>
  <li><strong>Add one</strong> with the Camera, the strip's IMG key, Start → ADD IMAGE, or paste or drop it into the text.</li>
  <li><strong>Each note picks one edge</strong> for its images: top or bottom (a scrapbook) or left or right (a strip beside the text, where the line next to an image is its caption). Start → IMAGE EDGE changes it.</li>
  <li><strong>Move one</strong> by tapping it or dragging it. The D-pad moves it a line at a time; <kbd class="a">A</kbd> is done, <kbd>B</kbd> cancels.</li>
  <li><strong>Replace or remove</strong> with the keys on the picked image, or with <kbd>START</kbd>. Removing asks first.</li>
</ul>

<h3>Planting a tree</h3>
<p>
  With the Map viewer in the bay, press <kbd class="key">MOVE</kbd>, move the cursor with the D-pad, the arrows or the mouse, and press
  <kbd class="a">A</kbd> to plant. With the mouse alone: click a tile, then click it again. Hover any tree to see its note's title, and click it to open that note.
  Without the Map viewer, a drawer slides out of the screen's right edge to do the same job.
</p>

<h3>Sorting and deleting notes</h3>
<p>
  The List module's tabs sort by <strong>SAVED</strong>, <strong>A–Z</strong> or <strong>MADE</strong>. To delete several notes, pick them: press
  <kbd>SELECT</kbd> in the list, slide up the switch under the tabs, or press and hold a row. <kbd class="a">A</kbd> picks a note, and
  <kbd>START</kbd> (or Delete) deletes the picked notes after a check that names them.
</p>

<h3>Making it yours</h3>
<p>
  The gear in the nameplate opens Configure. <strong>LAYOUT</strong> chooses which modules are slotted: the list, the D-pad, the controls,
  what the bay holds (Map viewer, Treemoji or List) and the speaker. Pull a module and the others take its room. <strong>LOOK</strong>
  chooses a theme and the finish. Configure isn't remembered between visits.
</p>

<h3>On a phone</h3>
<p>
  Hold it upright and the console stacks to fit. While the keyboard is up, only the screen and the controls row stay above it,
  so the D-pad or the Format deck is right by your thumbs. In portrait the list opens full screen, unless the bay holds it.
</p>

<h2><span class="no">05</span>Questions</h2>
<h3>Where are my notes?</h3>
<p>
  In this browser, on this device. Nothing is uploaded. Use Start → BACKUP → SAVE to keep a copy, and LOAD to bring it back.
</p>
<h3>Did I lose my note when I left?</h3>
<p>
  No. Leaving a note saves it, and so does closing the tab, switching apps, or opening one of these pages. A brand-new note with
  nothing in it is simply dropped.
</p>
<h3>Can I click the A and B labels on the screen?</h3>
<p>
  No, on purpose. They're labels that tell you what the keys do. Press the key on the console, use the keyboard, or click the
  thing on the screen itself. <a href="/about">The story</a> explains why.
</p>
